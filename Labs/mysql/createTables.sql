DROP DATABASE IF EXISTS conygre;

CREATE DATABASE IF NOT EXISTS conygre;
USE conygre;

CREATE TABLE compact_discs (
  id INT PRIMARY KEY AUTO_INCREMENT,
  title VARCHAR(50),
  artist VARCHAR(30),
  tracks INT,
  price DOUBLE
);

CREATE TABLE tracks (
  id INT PRIMARY KEY AUTO_INCREMENT,
  cd_id INT NOT NULL,
  title VARCHAR(50),
  FOREIGN KEY (cd_id) REFERENCES compact_discs(id)
);

